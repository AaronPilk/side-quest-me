// ---------------------------------------------------------------------------
// Filtering: the same hard rules the recommender applies, at the idea level.
// ---------------------------------------------------------------------------
export type IdeaConstraints = {
  category?: Category;
  intensity?: Intensity;
  setting?: Setting;
  group?: (typeof IDEA_GROUPS)[number];
  /** Maximum minutes available; unlimited when omitted. */
  maxMinutes?: number;
  /** Total budget in minor units; ideas costing more are excluded. */
  budgetMinor?: number;
  /** Firm boundaries; any idea declaring one of these conflicts is excluded. */
  exclusions?: Exclusion[];
  scopes?: IdeaScope[];
  themes?: IdeaTheme[];
};
export function filterQuestIdeas(
  constraints: IdeaConstraints,
  ideas: QuestIdea[] = questIdeas,
): QuestIdea[] {
  return ideas.filter((idea) => {
    if (constraints.category && idea.category !== constraints.category)
      return false;
    if (constraints.intensity && idea.intensity !== constraints.intensity)
      return false;
    if (constraints.setting && !idea.settings.includes(constraints.setting))
      return false;
    if (constraints.group && !idea.groups.includes(constraints.group))
      return false;
    if (
      constraints.maxMinutes !== undefined &&
      idea.minutes > constraints.maxMinutes
    )
      return false;
    if (
      constraints.budgetMinor !== undefined &&
      idea.cost.minMinor > constraints.budgetMinor
    )
      return false;
    if (constraints.exclusions?.some((rule) => idea.conflicts.includes(rule)))
      return false;
    if (constraints.scopes && !constraints.scopes.includes(idea.scope))
      return false;
    if (
      constraints.themes &&
      !constraints.themes.some((theme) => idea.themes.includes(theme))
    )
      return false;
    return true;
  });
}

