const boundedText = (max: number) => z.string().trim().min(1).max(max);
export const questIdeaSchema = z
  .object({
    id: z.string().regex(/^[a-z][a-z0-9_]{2,48}$/),
    text: boundedText(160),
    /** What a finished attempt can honestly show on camera. */
    evidence: boundedText(120),
    category: categorySchema,
    intensity: intensitySchema,
    scope: z.enum(IDEA_SCOPES),
    settings: z.array(settingSchema).min(1).max(3),
    groups: z.array(z.enum(IDEA_GROUPS)).min(1).max(3),
    minutes: z.number().int().min(5).max(720),
    cost: z
      .object({
        minMinor: z.number().int().nonnegative(),
        maxMinor: z.number().int().nonnegative(),
      })
      .strict(),
    interests: z.array(z.enum(IDEA_INTEREST_TAGS)).min(1).max(6),
    themes: z.array(z.enum(IDEA_THEMES)).min(1).max(5),
    /** Firm boundaries this idea would cross; hard filtered, never softened. */
    conflicts: z.array(exclusionSchema).max(8),
    /** Concrete briefs a person could pick, in the recipe's "prompt" voice. */
    briefs: z.array(boundedText(90)).min(1).max(6),
    /** Short, plain safety or permission note surfaced with any draft. */
    note: z.string().trim().max(240).default(""),
    /** Raw pool source ids (research/quest-ideas/raw-pool.json) that inspired it. */
    sources: z.array(z.string().max(40)).max(8).default([]),
  })
  .strict()
  .superRefine((idea, ctx) => {
    if (idea.cost.minMinor > idea.cost.maxMinor)
      ctx.addIssue({ code: "custom", path: ["cost"], message: "Invalid cost" });
    if (idea.category === "date_night" && !idea.groups.includes("couple"))
      ctx.addIssue({
        code: "custom",
        path: ["groups"],
        message: "Date Night ideas must work for a couple",
      });
    const limit = { moment: 15, session: 90, outing: 360, expedition: 720 }[
      idea.scope
    ];
    if (idea.minutes > limit)
      ctx.addIssue({
        code: "custom",
        path: ["minutes"],
        message: `A ${idea.scope} idea cannot exceed ${limit} minutes`,
      });
    if (
      idea.themes.includes("strangers") &&
      !idea.conflicts.includes("strangers")
    )
      ctx.addIssue({
        code: "custom",
        path: ["conflicts"],
        message:
          "Ideas that involve strangers must declare the strangers boundary",
      });
  });
export type QuestIdea = z.infer<typeof questIdeaSchema>;

type IdeaInput = Omit<z.input<typeof questIdeaSchema>, "cost"> & {
  cost?: [number, number];
};
const idea = (input: IdeaInput): QuestIdea =>
  questIdeaSchema.parse({
    ...input,
    cost: { minMinor: input.cost?.[0] ?? 0, maxMinor: input.cost?.[1] ?? 0 },
  });
